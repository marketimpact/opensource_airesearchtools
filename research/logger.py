"""Append findings to the master markdown file and write run logs."""

import logging
from datetime import datetime, timezone
from pathlib import Path

log = logging.getLogger(__name__)

HEADER = """\
# Iran Conflict: Secondary Global Impacts — Research Log

> Auto-generated by research agent. Last updated: {timestamp}

"""


def append_findings(findings: list[dict], findings_path: Path):
    """Append new findings to the master markdown file, grouped by category."""
    if not findings:
        log.info("  No new findings to log")
        return

    findings_path.parent.mkdir(parents=True, exist_ok=True)
    now = datetime.now(timezone.utc)
    today = now.strftime("%Y-%m-%d")
    timestamp = now.strftime("%Y-%m-%d %H:%M UTC")

    # Read existing content to check if today's date header exists
    existing = ""
    if findings_path.exists():
        existing = findings_path.read_text()

    # If file doesn't exist or is empty, write the header
    if not existing.strip():
        existing = HEADER.format(timestamp=timestamp)

    # Update the "Last updated" timestamp
    if "Last updated:" in existing:
        lines = existing.split("\n")
        for i, line in enumerate(lines):
            if "Last updated:" in line:
                lines[i] = f"> Auto-generated by research agent. Last updated: {timestamp}"
                break
        existing = "\n".join(lines)

    # Group findings by category
    by_category: dict[str, list[dict]] = {}
    for f in findings:
        cat = f.get("category", "Uncategorized")
        by_category.setdefault(cat, []).append(f)

    # Build new markdown content
    new_sections = []

    # Check if today's date section already exists
    date_header = f"## {today}"
    has_today = date_header in existing

    if not has_today:
        new_sections.append(f"\n---\n\n{date_header}\n")

    for category, cat_findings in by_category.items():
        new_sections.append(f"\n### {category}\n")
        for f in cat_findings:
            new_sections.append(_format_finding(f))

    new_content = "\n".join(new_sections)

    if has_today:
        # Append under today's existing section (before the next date section or at end)
        # Find the position after the today header
        idx = existing.index(date_header) + len(date_header)
        # Find the next date header (## YYYY-MM-DD) or end of file
        next_date_idx = existing.find("\n## 20", idx + 1)
        if next_date_idx == -1:
            # Append at end
            existing = existing.rstrip() + "\n" + new_content + "\n"
        else:
            # Insert before the next date section
            existing = existing[:next_date_idx] + new_content + "\n" + existing[next_date_idx:]
    else:
        # Insert new date section after the header block
        # Find the first --- or ## to insert before, or append
        header_end = existing.find("\n---\n")
        if header_end != -1 and header_end > 10:
            # Insert after header, before first existing date section
            existing = existing[:header_end] + new_content + "\n" + existing[header_end:]
        else:
            existing = existing.rstrip() + "\n" + new_content + "\n"

    findings_path.write_text(existing)
    log.info(f"  Logged {len(findings)} findings to {findings_path}")


def _format_finding(f: dict) -> str:
    """Format a single finding as markdown."""
    # Quality score line
    composite = f.get("composite_score", 0)
    tier = f.get("quality_tier", "Unscored")
    scores = f.get("scores", {})

    score_detail = " | ".join(
        f"{dim[:3].title()}: {val}"
        for dim, val in [
            ("source_reliability", scores.get("source_reliability", "?")),
            ("corroboration", scores.get("corroboration", "?")),
            ("specificity", scores.get("specificity", "?")),
            ("recency", scores.get("recency", "?")),
            ("geographic_relevance", scores.get("geographic_relevance", "?")),
        ]
    )

    lines = [
        f"\n#### {f.get('title', 'Untitled')}",
        f"- **Date observed:** {f.get('date_observed', 'unknown')}",
        f"- **Source:** {f.get('source_name', 'Unknown')} ({f.get('source_language', '?')}) -- {f.get('source_url', 'N/A')}",
        f"- **Quality:** {tier} ({composite}/5.0)",
        f"- **Scores:** {score_detail}",
        f"- **Details:** {f.get('details', 'No details')}",
        f"- **Impact type:** {f.get('impact_type', 'Unclassified')}",
        f"- **Related regions:** {', '.join(f.get('related_regions', ['Unknown']))}",
        "",
    ]
    return "\n".join(lines)


def write_run_log(log_dir: Path, stats: dict):
    """Write a per-run log file with stats."""
    log_dir.mkdir(parents=True, exist_ok=True)
    now = datetime.now(timezone.utc)
    filename = now.strftime("%Y-%m-%d_%H%M%S.log")
    log_path = log_dir / filename

    tier_counts = stats.get("tier_counts", {})
    lines = [
        f"Research Agent Run Log -- {now.strftime('%Y-%m-%d %H:%M:%S UTC')}",
        "=" * 60,
        f"Categories searched:    {stats.get('categories_searched', 0)}",
        f"Queries executed:       {stats.get('queries_executed', 0)}",
        f"Search results found:   {stats.get('search_results', 0)}",
        f"Findings extracted:     {stats.get('findings_extracted', 0)}",
        "",
        "Scoring breakdown:",
        f"  Verified (>=4.0):     {tier_counts.get('Verified', 0)}",
        f"  Likely (3.0-3.9):     {tier_counts.get('Likely', 0)}",
        f"  Unverified (2.0-2.9): {tier_counts.get('Unverified', 0)}",
        f"  Unreliable (<2.0):    {tier_counts.get('Unreliable', 0)}  [rejected]",
        f"  Average composite:    {stats.get('avg_composite_score', 0)}",
        "",
        f"Findings rejected:      {stats.get('findings_rejected', 0)}",
        f"Duplicates skipped:     {stats.get('duplicates_skipped', 0)}",
        f"New findings logged:    {stats.get('new_findings', 0)}",
        f"Contradictions:         {stats.get('contradictions_detected', 0)}",
        f"Errors:                 {stats.get('errors', 0)}",
        "",
    ]

    # Add rejected findings detail
    rejected = stats.get("rejected_findings", [])
    if rejected:
        lines.append("Rejected findings (unreliable):")
        for r in rejected:
            lines.append(f"  - \"{r.get('title', '?')}\" (score: {r.get('score', '?')}, source: {r.get('source', '?')})")
        lines.append("")
    log_path.write_text("\n".join(lines))
    log.info(f"  Run log written to {log_path}")
